// Replay unchanged historical briefs, varying only the two owned builders and their block parents.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { gzipSync, gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { acquireMachineLock } from '../../../tests/helpers/machine-lock.js';
const [source, evidence, output] = process.argv.slice(2);
if (!output) throw Error('Usage: capture.mjs SOURCE EXTRACTED_EVIDENCE NEW_OUTPUT');
const load = f => import(pathToFileURL(path.resolve(source, f)));
const { readChainMap, chainMapToJson } = await load('map/macro/src/chain/saving.ts');
const { buildRegion } = await load('map/micro/region-types.ts');
const { auditMap } = await load('tools/incidental-seam-audit.mjs');
const { measureSeamRoutes } = await load('tools/incidental-seam-routes.mjs');
const hash = b => createHash('sha256').update(b).digest('hex');
const sourceHashes = {};
function scan(dir) {
  for (const item of fs.readdirSync(path.resolve(source, dir), { withFileTypes: true })) {
    const f = `${dir}/${item.name}`;
    if (item.isDirectory()) scan(f); else sourceHashes[f] = hash(fs.readFileSync(path.resolve(source, f)));
  }
}
scan('map'); scan('shared');
for (const f of ['tools/incidental-seam-audit.mjs', 'tools/incidental-seam-routes.mjs']) sourceHashes[f] = hash(fs.readFileSync(path.resolve(source, f)));
fs.mkdirSync(output);
const report = { version: 'issue-716-readiness-capture-1', sourceHashes, node: process.version,
  protocolSha256: hash(fs.readFileSync(new URL('./protocol.json', import.meta.url))), cases: [] };
const lock = await acquireMachineLock('bench', { timeoutMs: 30 * 60_000, pollMs: 100 });
try {
  for (const width of [12, 24, 36]) for (let i = 1; i <= 3; i++) {
    const seed = `size-${width}-${i}`, inputs = {};
    const read = file => { const bytes = fs.readFileSync(path.resolve(evidence, file)); inputs[file] = hash(bytes); return bytes; };
    const map = readChainMap(gunzipSync(read(`baseline/${seed}.json.gz`)));
    const fixedBytes = read(`baseline/${seed}-endpoints.json`), endpoints = JSON.parse(fixedBytes);
    const rows = [], started = performance.now();
    map.results = map.results.map((r, index) => {
      if (!['depot', 'market', 'block'].includes(r.brief.type)) return r;
      const tick = performance.now(), next = buildRegion(structuredClone(r.brief));
      if (JSON.stringify(next.brief) !== JSON.stringify(r.brief)) throw Error('Brief changed');
      if (JSON.stringify(next.coreElements) !== JSON.stringify(r.coreElements)) throw Error('Core sites changed');
      rows.push({ index, id: r.brief.id, type: r.brief.type, ms: performance.now() - tick, manifest: next.manifest });
      return next;
    });
    const buildMs = performance.now() - started;
    // Full saved results are authoritative; this mixed historical experiment cannot be regenerated by a production identity.
    map.build = 'issue-716-readiness-frontage-1';
    const saved = Buffer.from(chainMapToJson(map));
    const audit = auditMap(map, endpoints), routes = measureSeamRoutes(map, endpoints, audit);
    const artifacts = [
      [`${seed}.json.gz`, gzipSync(saved)], [`${seed}-endpoints.json`, fixedBytes],
      [`${seed}-seams.json.gz`, gzipSync(JSON.stringify({ ...audit, endpoints: undefined }))],
      [`${seed}-routes.json`, Buffer.from(JSON.stringify(routes) + '\n')],
    ];
    for (const [f, bytes] of artifacts) fs.writeFileSync(path.resolve(output, f), bytes, { flag: 'wx' });
    report.cases.push({ seed, inputHashes: inputs, buildMs, rows, artifacts: Object.fromEntries(artifacts.map(([f, b]) => [f, hash(b)])),
      bodies: Object.fromEntries(Object.entries(routes.bodies).map(([k, { routes, ...v }]) => [k, v])) });
    fs.writeFileSync(path.resolve(output, 'manifest.json'), JSON.stringify(report, null, 2) + '\n');
    console.log(JSON.stringify({ seed, buildMs, changedOwners: rows.length, bodies: report.cases.at(-1).bodies }));
  }
  for (const [f, h] of Object.entries(sourceHashes)) if (hash(fs.readFileSync(path.resolve(source, f))) !== h) throw Error(`Source changed during capture: ${f}`);
  report.complete = true;
  fs.writeFileSync(path.resolve(output, 'manifest.json'), JSON.stringify(report, null, 2) + '\n');
} finally { lock.release(); }
