// Builds the Rust core to WASM (docs/27). The module is a build output, never committed: every host
// builds its own, and tests/math.test.js's digests check that it computes what shared/math.ts does.
// Its bytes need not match another machine's; its results must.
//
//   npm run core:build    build it; Cargo makes this a no-op when nothing changed
//
// Callers import buildCore, which builds once per process and returns the module's path.
//
// It also writes the module's bytes into CORE_EMBEDDED, a generated TypeScript module that
// shared/core.ts's initCore imports, so Node and the browser load the core the same way, as
// Rapier's -compat package does: no file read in one host and fetch in the other (docs/27).
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
/** Where Cargo writes the module. */
export const CORE_WASM = path.join(root, 'rust/target/wasm32-unknown-unknown/release/last_exit_core.wasm');
/** The module's bytes as base64, for shared/core.ts's initCore. Ignored by git. */
export const CORE_EMBEDDED = path.join(root, 'shared/core-wasm.generated.ts');

let built = false;

export function buildCore() {
  if (built) return CORE_WASM;
  const result = spawnSync('cargo', ['build', '--locked', '--release', '-p', 'last-exit-core', '--target', 'wasm32-unknown-unknown'],
    { cwd: path.join(root, 'rust'), stdio: ['ignore', 'inherit', 'pipe'], encoding: 'utf8' });
  if (result.error) throw new Error(`cannot run cargo (${result.error.message}); install the toolchain rust/rust-toolchain.toml names`);
  if (result.status !== 0) throw new Error(`building the core failed:\n${result.stderr}`);
  embed();
  built = true;
  return CORE_WASM;
}

/** Rewrite CORE_EMBEDDED only when the bytes changed, through a rename, so a concurrent reader sees a whole file. */
function embed() {
  const source = '// Generated by tools/build-core.mjs from the core\'s WASM module; do not edit or commit (docs/27).\n'
    + `export const CORE_WASM_BASE64 = '${readFileSync(CORE_WASM).toString('base64')}';\n`;
  if (existsSync(CORE_EMBEDDED) && readFileSync(CORE_EMBEDDED, 'utf8') === source) return;
  const temporary = `${CORE_EMBEDDED}.${process.pid}.tmp`;
  writeFileSync(temporary, source);
  renameSync(temporary, CORE_EMBEDDED);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    console.log(`built ${path.relative(root, buildCore())}`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
